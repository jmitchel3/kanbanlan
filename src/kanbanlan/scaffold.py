from kanbanlan.config import CONFIG_FILENAME, Config

START_MARKER = "<!-- kanbanlan:start -->"
END_MARKER = "<!-- kanbanlan:end -->"
MANAGED_FILE_MARKER = "<!-- Generated by kanbanlan; run `kanbanlan init` to refresh. -->"
YAML_MANAGED_FILE_MARKER = "# Generated by kanbanlan; run `kanbanlan init` to refresh."

